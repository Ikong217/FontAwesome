    /**
     * Get the outlined (far) version of this icon, if one exists.
     * Returns null when the icon has no regular/outlined counterpart
     * (most Font Awesome Free icons only ship as solid).
     */
    public function outlined(): ?self
    {
        if (str_starts_with($this->value, 'far-')) {
            return $this; // already outlined
        }

        $outlinedValue = str_replace('fas-', 'far-', $this->value);

        return self::tryFrom($outlinedValue);
    }

    /**
     * Get the solid (fas) version of this icon.
     */
    public function solid(): ?self
    {
        if (str_starts_with($this->value, 'fas-')) {
            return $this;
        }

        $solidValue = str_replace('far-', 'fas-', $this->value);

        return self::tryFrom($solidValue);
    }

    /**
     * Whether this icon has an outlined (far) counterpart.
     */
    public function hasOutline(): bool
    {
        return $this->outlined() !== null;
    }

    /**
     * Bare icon name without the fas-/far- style prefix.
     */
    public function iconName(): string
    {
        return substr($this->value, 4);
    }

    public function getIconClass(): string
    {
        $style = str_starts_with($this->value, 'far-') ? 'far' : 'fas';
        return "{$style} fa-{$this->iconName()}";
    }

    public function getSizeClass(IconSize $size): string
    {
        return match ($size) {
            IconSize::ExtraSmall    => 'fa-xs',
            IconSize::Small         => 'fa-sm',
            IconSize::Medium        => '', // default size
            IconSize::Large         => 'fa-lg',
            IconSize::ExtraLarge    => 'fa-xl',
            IconSize::TwoExtraLarge => 'fa-2xl',
        };
    }

    public function getIconForSize(IconSize $size): string
    {
        return trim($this->getIconClass() . ' ' . $this->getSizeClass($size));
    }
    public function sizeClass(IconSize $size): string
    {
        return match ($size) {
            IconSize::ExtraSmall    => 'w-3 h-3',
            IconSize::Small         => 'w-4 h-4',
            IconSize::Medium        => 'w-5 h-5',
            IconSize::Large         => 'w-6 h-6',
            IconSize::ExtraLarge    => 'w-8 h-8',
            IconSize::TwoExtraLarge => 'w-10 h-10',
        };
    }
